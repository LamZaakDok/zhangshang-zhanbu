#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
中文字库子集生成器
====================
扫描 data/ 与 src/ 下所有文本, 收集用到的字符(含 ASCII 可打印区),
用指定字体渲染成 16x16 单色点阵, 输出 src/cnfont_generated.h。

默认使用 **GNU Unifont** —— 它本身就是 16x16 点阵设计, 覆盖整个 Unicode BMP,
在 16px 下笔画清晰、不缺字。若字体文件不存在会自动下载。

依赖: pip install pillow
用法:
    python tools/gen_font.py                 # 自动用 tools/raw/unifont.otf
    python tools/gen_font.py --ttf 某字体.otf
"""
import argparse
import glob
import os
import ssl
import sys
import urllib.request

try:
    from PIL import Image, ImageDraw, ImageFont
except ImportError:
    sys.exit("需要 Pillow: pip install pillow")

UNIFONT_URL = "https://unifoundry.com/pub/unifont/unifont-15.1.05/font-builds/unifont-15.1.05.otf"
UNIFONT_PATH = os.path.join("tools", "raw", "unifont.otf")


def ensure_ttf(path):
    if os.path.exists(path):
        return path
    if os.path.abspath(path) != os.path.abspath(UNIFONT_PATH):
        sys.exit("字体不存在: %s" % path)
    os.makedirs(os.path.dirname(path), exist_ok=True)
    print("下载 Unifont ...")
    ctx = ssl.create_default_context()
    ctx.check_hostname = False
    ctx.verify_mode = ssl.CERT_NONE
    req = urllib.request.Request(UNIFONT_URL, headers={"User-Agent": "Mozilla/5.0"})
    with urllib.request.urlopen(req, timeout=180, context=ctx) as r:
        data = r.read()
    with open(path, "wb") as f:
        f.write(data)
    print("已保存 %s (%.1f MB)" % (path, len(data) / 1024 / 1024))
    return path


def collect_chars(paths):
    chars = set(chr(c) for c in range(0x20, 0x7F))   # ASCII 可打印
    for p in paths:
        with open(p, encoding="utf-8") as f:
            for ch in f.read():
                if ord(ch) >= 0x80:
                    chars.add(ch)
    return chars


def render_glyph(font, ch, size, thr):
    img = Image.new("L", (size, size), 0)
    ImageDraw.Draw(img).text((0, 0), ch, fill=255, font=font)
    px = img.load()
    rows = []
    for y in range(size):
        row = 0
        for x in range(size):
            if px[x, y] > thr:
                row |= (1 << (size - 1 - x))
        rows.append(row)
    return rows


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--ttf", default=UNIFONT_PATH)
    ap.add_argument("--data", default="data")
    ap.add_argument("--src", default="src")
    ap.add_argument("--out", default="src/cnfont_generated.h")
    ap.add_argument("--size", type=int, default=16)
    ap.add_argument("--thr", type=int, default=128)
    a = ap.parse_args()

    if a.size != 16:
        sys.exit("当前 ui.cpp 仅支持 16x16 点阵 (--size 16)")

    ttf = ensure_ttf(a.ttf)

    files = sorted(glob.glob(os.path.join(a.data, "**", "*.csv"), recursive=True))
    files += sorted(glob.glob(os.path.join(a.data, "**", "*.txt"), recursive=True))
    files += sorted(glob.glob(os.path.join(a.src, "**", "*.cpp"), recursive=True))
    files += sorted(glob.glob(os.path.join(a.src, "**", "*.h"), recursive=True))
    files = [f for f in files if os.path.basename(f) != "cnfont_generated.h"]

    chars = sorted(collect_chars(files), key=ord)
    font = ImageFont.truetype(ttf, a.size)
    glyph_bytes = (a.size // 8) * a.size

    out = ["// AUTO-GENERATED by tools/gen_font.py — 请勿手工编辑。",
           "#pragma once", "#include <stdint.h>",
           "struct CnGlyph { uint32_t cp; uint8_t bmp[%d]; };" % glyph_bytes,
           "static const uint16_t CN_FONT_W = %d;" % a.size,
           "static const uint16_t CN_FONT_H = %d;" % a.size,
           "static const CnGlyph CN_FONT[] = {"]
    empty = []
    for ch in chars:
        rows = render_glyph(font, ch, a.size, a.thr)
        if not any(rows) and not ch.isspace():
            empty.append(ch)
        data = []
        for r in rows:
            data.append((r >> 8) & 0xFF)
            data.append(r & 0xFF)
        out.append("  {0x%04X,{%s}}," % (ord(ch), ",".join("0x%02X" % b for b in data)))
    out.append("};")
    out.append("static const int CN_FONT_COUNT = %d;" % len(chars))

    os.makedirs(os.path.dirname(a.out), exist_ok=True)
    with open(a.out, "w", encoding="utf-8") as f:
        f.write("\n".join(out) + "\n")

    print("字体: %s" % ttf)
    print("扫描 %d 个文件, 嵌入 %d 个字形 -> %s (~%d KB)"
          % (len(files), len(chars), a.out, len(chars) * glyph_bytes // 1024))
    if empty:
        print("警告: %d 字缺字(将显示空白): %s" % (len(empty), "".join(empty[:80])))


if __name__ == "__main__":
    main()
